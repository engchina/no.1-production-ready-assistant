-- DB 管理の操作の監査（#2264）。DB 管理チャット・管理 SQL を実行・テーブル / ビュー / データの管理の
-- 実行を 1 行ずつ残す（件数の上限は持たない）。SQL の全文・文の種類・確認語・結果・影響行数・時間を持つ。
CREATE TABLE NL2SQL_ADMIN_AUDIT_LOG (
    AUDIT_ID VARCHAR2(36) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    SOURCE VARCHAR2(40) NOT NULL,
    OPERATION VARCHAR2(80) NOT NULL,
    TARGET VARCHAR2(512),
    ACTOR_USER_UUID VARCHAR2(64),
    ACTOR_IS_SYSTEM_ADMIN NUMBER(1) DEFAULT 0 NOT NULL,
    OUTCOME VARCHAR2(20) NOT NULL,
    EXECUTED NUMBER(1) DEFAULT 0 NOT NULL,
    CONFIRMATION_GIVEN NUMBER(1) DEFAULT 0 NOT NULL,
    COMMITTED NUMBER(1) DEFAULT 0 NOT NULL,
    ROLLED_BACK NUMBER(1) DEFAULT 0 NOT NULL,
    STATEMENT_COUNT NUMBER(10) DEFAULT 0 NOT NULL,
    SUCCESS_COUNT NUMBER(10) DEFAULT 0 NOT NULL,
    STATEMENT_TYPES VARCHAR2(4000),
    AFFECTED_ROWS NUMBER(19),
    DURATION_MS NUMBER(19),
    REASON VARCHAR2(2000),
    ERROR_MESSAGE VARCHAR2(4000),
    SQL_TEXT CLOB,
    DETAIL_JSON CLOB,
    CONSTRAINT PK_NL2SQL_ADMIN_AUDIT_LOG PRIMARY KEY (AUDIT_ID),
    CONSTRAINT CK_NL2SQL_ADMIN_AUDIT_OUTCOME CHECK (
        OUTCOME IN ('success', 'partial', 'failure', 'blocked')
    ),
    CONSTRAINT CK_NL2SQL_ADMIN_AUDIT_DETAIL CHECK (DETAIL_JSON IS JSON)
);
CREATE INDEX IX_NL2SQL_ADMIN_AUDIT_TIME ON NL2SQL_ADMIN_AUDIT_LOG(CREATED_AT);
CREATE INDEX IX_NL2SQL_ADMIN_AUDIT_ACTOR ON NL2SQL_ADMIN_AUDIT_LOG(ACTOR_USER_UUID, CREATED_AT);
