CREATE TABLE NL2SQL_DB_ADMIN_CHATS (
    CONVERSATION_ID VARCHAR2(64) NOT NULL,
    OWNER_USER_UUID VARCHAR2(64) NOT NULL,
    TITLE VARCHAR2(400 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_NL2SQL_DB_ADMIN_CHATS PRIMARY KEY (CONVERSATION_ID)
);
CREATE TABLE NL2SQL_DB_ADMIN_CHAT_TURNS (
    TURN_ID VARCHAR2(64) NOT NULL,
    CONVERSATION_ID VARCHAR2(64) NOT NULL,
    TURN_NO NUMBER(10) NOT NULL,
    SENDER_USER_UUID VARCHAR2(64),
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    TURN_JSON CLOB NOT NULL,
    CONSTRAINT PK_NL2SQL_DB_ADMIN_CHAT_TURNS PRIMARY KEY (TURN_ID),
    CONSTRAINT FK_NL2SQL_DB_ADMIN_CHAT_TURN FOREIGN KEY (CONVERSATION_ID)
        REFERENCES NL2SQL_DB_ADMIN_CHATS (CONVERSATION_ID) ON DELETE CASCADE,
    CONSTRAINT CK_NL2SQL_DB_ADMIN_CHAT_TURN_JSON CHECK (TURN_JSON IS JSON)
);
CREATE INDEX IX_NL2SQL_DB_ADMIN_CHAT_OWNER ON NL2SQL_DB_ADMIN_CHATS (OWNER_USER_UUID, CREATED_AT);
CREATE INDEX IX_NL2SQL_DB_ADMIN_CHAT_TIME ON NL2SQL_DB_ADMIN_CHATS (CREATED_AT);
CREATE INDEX IX_NL2SQL_DB_ADMIN_CHAT_TURN_CONV ON NL2SQL_DB_ADMIN_CHAT_TURNS (CONVERSATION_ID, TURN_NO);
