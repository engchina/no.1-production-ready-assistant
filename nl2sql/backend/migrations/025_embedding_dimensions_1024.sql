-- 埋め込みの次元を 1536 から 1024（pr_system_settings.embedding の EMBEDDING_DIMENSIONS）へ変える（#46）。
-- Oracle のベクトル列は次元を変えられないため、次元が違う（#46 より前の 1536）ときだけ作り直す。
-- 既に 1024 なら何もしない（新しい環境は 001 が 1024 で作る）。次元は USER_TAB_COLUMNS.VECTOR_INFO
-- （例 VECTOR(1024,FLOAT32,DENSE)）で読む。
-- - NL2SQL_ONTOLOGY_NODES.EMBEDDING: HNSW 索引と列を削除し、1024 次元の列と索引を作る。ノードの
--   埋め込みは消え、オントロジーの検索は次の構築・公開で埋め込み直すまで語の一致だけになる。
-- - NL2SQL_FEEDBACK_VECTORS（feedback の学習の索引。履歴から作り直せる派生のデータ）: 表を削除する。
--   次の「feedback index の再構築」が 1024 次元で作り直す。
DECLARE
    v_vector_info VARCHAR2(256);
    v_count NUMBER;
BEGIN
    SELECT MAX(VECTOR_INFO) INTO v_vector_info
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'NL2SQL_ONTOLOGY_NODES' AND COLUMN_NAME = 'EMBEDDING';
    IF v_vector_info IS NOT NULL
        AND REPLACE(v_vector_info, ' ', '') NOT LIKE 'VECTOR(1024,FLOAT32%' THEN
        SELECT COUNT(*) INTO v_count FROM USER_INDEXES
        WHERE INDEX_NAME = 'IX_NL2SQL_ONT_NODE_EMBED';
        IF v_count > 0 THEN
            EXECUTE IMMEDIATE 'DROP INDEX IX_NL2SQL_ONT_NODE_EMBED';
        END IF;
        EXECUTE IMMEDIATE 'ALTER TABLE NL2SQL_ONTOLOGY_NODES DROP COLUMN EMBEDDING';
        EXECUTE IMMEDIATE 'ALTER TABLE NL2SQL_ONTOLOGY_NODES ADD (EMBEDDING VECTOR(1024, FLOAT32))';
        EXECUTE IMMEDIATE 'CREATE VECTOR INDEX IX_NL2SQL_ONT_NODE_EMBED '
            || 'ON NL2SQL_ONTOLOGY_NODES (EMBEDDING) '
            || 'ORGANIZATION INMEMORY NEIGHBOR GRAPH DISTANCE COSINE';
    END IF;
    SELECT MAX(VECTOR_INFO) INTO v_vector_info
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'NL2SQL_FEEDBACK_VECTORS' AND COLUMN_NAME = 'EMBEDDING';
    IF v_vector_info IS NOT NULL
        AND REPLACE(v_vector_info, ' ', '') NOT LIKE 'VECTOR(1024,FLOAT32%' THEN
        EXECUTE IMMEDIATE 'DROP TABLE NL2SQL_FEEDBACK_VECTORS CASCADE CONSTRAINTS PURGE';
    END IF;
END;
