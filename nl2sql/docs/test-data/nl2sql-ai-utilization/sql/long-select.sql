SELECT o.ORDER_ID, o.CUSTOMER_ID, c.CUSTOMER_NAME, o.ORDER_DATE, o.STATUS, o.TOTAL_AMOUNT, i.INVOICE_ID, i.STATUS AS INVOICE_STATUS, i.DUE_DATE, i.TOTAL_AMOUNT AS INVOICE_TOTAL_AMOUNT
FROM APP.ORDERS o
JOIN APP.CUSTOMERS c ON c.CUSTOMER_ID = o.CUSTOMER_ID
LEFT JOIN APP.INVOICES i ON i.CUSTOMER_ID = o.CUSTOMER_ID
WHERE o.ORDER_DATE >= DATE '2026-08-01'
  AND o.STATUS IN ('OPEN', 'CLOSED')
  AND (i.STATUS = 'UNPAID' OR i.STATUS IS NULL)
ORDER BY o.TOTAL_AMOUNT DESC, o.ORDER_DATE DESC, c.CUSTOMER_NAME ASC
FETCH FIRST 100 ROWS ONLY;

