DECLARE
  PROCEDURE drop_if_exists(p_sql IN VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_sql;
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE NOT IN (-942, -4043) THEN
        RAISE;
      END IF;
  END drop_if_exists;
BEGIN
  drop_if_exists('DROP VIEW V_TD_NL2SQL_REVIEW_QUEUE');
  drop_if_exists('DROP VIEW V_TD_NL2SQL_OPEN_ORDERS');
  drop_if_exists('DROP VIEW V_TD_NL2SQL_CUSTOMER_SALES');
  drop_if_exists('DROP VIEW V_TD_NL2SQL_ORDER_SUMMARY');
  drop_if_exists('DROP TABLE TD_NL2SQL_IMPORTED_QUOTES CASCADE CONSTRAINTS PURGE');
  drop_if_exists('DROP TABLE TD_NL2SQL_ORDER_LINES CASCADE CONSTRAINTS PURGE');
  drop_if_exists('DROP TABLE TD_NL2SQL_ORDERS CASCADE CONSTRAINTS PURGE');
  drop_if_exists('DROP TABLE TD_NL2SQL_AUDIT_EVENTS CASCADE CONSTRAINTS PURGE');
  drop_if_exists('DROP TABLE TD_NL2SQL_PRODUCTS CASCADE CONSTRAINTS PURGE');
  drop_if_exists('DROP TABLE TD_NL2SQL_CUSTOMERS CASCADE CONSTRAINTS PURGE');
  drop_if_exists('DROP TABLE TD_NL2SQL_DEPARTMENTS CASCADE CONSTRAINTS PURGE');
END /* cleanup */;
