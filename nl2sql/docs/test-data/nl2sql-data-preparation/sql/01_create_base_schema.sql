CREATE TABLE TD_NL2SQL_DEPARTMENTS (
    DEPARTMENT_ID NUMBER PRIMARY KEY,
    DEPARTMENT_CODE VARCHAR2(20) NOT NULL UNIQUE,
    DEPARTMENT_NAME VARCHAR2(100) NOT NULL,
    REGION VARCHAR2(30) NOT NULL,
    ACTIVE_FLAG CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT CK_TD_NL2SQL_DEPT_ACTIVE CHECK (ACTIVE_FLAG IN ('Y', 'N'))
);

CREATE TABLE TD_NL2SQL_CUSTOMERS (
    CUSTOMER_ID NUMBER PRIMARY KEY,
    CUSTOMER_NAME VARCHAR2(120) NOT NULL,
    SEGMENT VARCHAR2(30) NOT NULL,
    PREFECTURE VARCHAR2(30) NOT NULL,
    CREDIT_LIMIT NUMBER(12,2) DEFAULT 0 NOT NULL,
    RISK_RANK VARCHAR2(10) DEFAULT 'B' NOT NULL,
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT CK_TD_NL2SQL_CUSTOMER_RISK CHECK (RISK_RANK IN ('A', 'B', 'C'))
);

CREATE TABLE TD_NL2SQL_PRODUCTS (
    PRODUCT_ID NUMBER PRIMARY KEY,
    SKU VARCHAR2(30) NOT NULL UNIQUE,
    PRODUCT_NAME VARCHAR2(120) NOT NULL,
    CATEGORY VARCHAR2(50) NOT NULL,
    UNIT_PRICE NUMBER(12,2) NOT NULL,
    ACTIVE_FLAG CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT CK_TD_NL2SQL_PRODUCT_ACTIVE CHECK (ACTIVE_FLAG IN ('Y', 'N'))
);

CREATE TABLE TD_NL2SQL_ORDERS (
    ORDER_ID NUMBER PRIMARY KEY,
    CUSTOMER_ID NUMBER NOT NULL,
    OWNER_DEPARTMENT_ID NUMBER NOT NULL,
    ORDER_DATE DATE NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    CHANNEL VARCHAR2(20) NOT NULL,
    TOTAL_AMOUNT NUMBER(12,2) DEFAULT 0 NOT NULL,
    UPDATED_AT DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_TD_NL2SQL_ORDERS_CUSTOMER FOREIGN KEY (CUSTOMER_ID)
        REFERENCES TD_NL2SQL_CUSTOMERS(CUSTOMER_ID),
    CONSTRAINT FK_TD_NL2SQL_ORDERS_DEPT FOREIGN KEY (OWNER_DEPARTMENT_ID)
        REFERENCES TD_NL2SQL_DEPARTMENTS(DEPARTMENT_ID),
    CONSTRAINT CK_TD_NL2SQL_ORDER_STATUS CHECK (STATUS IN ('NEW', 'REVIEW', 'APPROVED', 'SHIPPED', 'CANCELLED'))
);

CREATE TABLE TD_NL2SQL_ORDER_LINES (
    LINE_ID NUMBER PRIMARY KEY,
    ORDER_ID NUMBER NOT NULL,
    PRODUCT_ID NUMBER NOT NULL,
    QUANTITY NUMBER(10,2) NOT NULL,
    UNIT_PRICE NUMBER(12,2) NOT NULL,
    DISCOUNT_RATE NUMBER(5,2) DEFAULT 0 NOT NULL,
    LINE_AMOUNT NUMBER(12,2) NOT NULL,
    CONSTRAINT FK_TD_NL2SQL_LINES_ORDER FOREIGN KEY (ORDER_ID)
        REFERENCES TD_NL2SQL_ORDERS(ORDER_ID),
    CONSTRAINT FK_TD_NL2SQL_LINES_PRODUCT FOREIGN KEY (PRODUCT_ID)
        REFERENCES TD_NL2SQL_PRODUCTS(PRODUCT_ID),
    CONSTRAINT CK_TD_NL2SQL_LINES_QTY CHECK (QUANTITY > 0)
);

CREATE TABLE TD_NL2SQL_AUDIT_EVENTS (
    EVENT_ID NUMBER PRIMARY KEY,
    EVENT_TIME TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    ACTOR VARCHAR2(80) NOT NULL,
    ACTION_NAME VARCHAR2(80) NOT NULL,
    OBJECT_NAME VARCHAR2(128) NOT NULL,
    NOTE VARCHAR2(400)
);
