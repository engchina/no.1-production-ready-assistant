CREATE OR REPLACE VIEW V_TD_NL2SQL_ORDER_SUMMARY AS
SELECT
    o.ORDER_ID,
    o.ORDER_DATE,
    o.STATUS,
    o.CHANNEL,
    o.TOTAL_AMOUNT,
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    c.SEGMENT,
    c.PREFECTURE,
    d.DEPARTMENT_NAME,
    COUNT(l.LINE_ID) AS LINE_COUNT,
    SUM(l.QUANTITY) AS TOTAL_QUANTITY,
    CASE
        WHEN o.STATUS = 'CANCELLED' THEN '除外'
        WHEN o.TOTAL_AMOUNT >= 1000000 THEN '重点'
        ELSE '通常'
    END AS BUSINESS_PRIORITY
FROM TD_NL2SQL_ORDERS o
JOIN TD_NL2SQL_CUSTOMERS c
  ON o.CUSTOMER_ID = c.CUSTOMER_ID
JOIN TD_NL2SQL_DEPARTMENTS d
  ON o.OWNER_DEPARTMENT_ID = d.DEPARTMENT_ID
LEFT JOIN TD_NL2SQL_ORDER_LINES l
  ON o.ORDER_ID = l.ORDER_ID
GROUP BY
    o.ORDER_ID,
    o.ORDER_DATE,
    o.STATUS,
    o.CHANNEL,
    o.TOTAL_AMOUNT,
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    c.SEGMENT,
    c.PREFECTURE,
    d.DEPARTMENT_NAME;

CREATE OR REPLACE VIEW V_TD_NL2SQL_CUSTOMER_SALES AS
SELECT
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    c.SEGMENT,
    c.PREFECTURE,
    c.RISK_RANK,
    COUNT(o.ORDER_ID) AS ORDER_COUNT,
    SUM(CASE WHEN o.STATUS <> 'CANCELLED' THEN o.TOTAL_AMOUNT ELSE 0 END) AS ACTIVE_SALES_AMOUNT,
    MAX(o.ORDER_DATE) AS LAST_ORDER_DATE
FROM TD_NL2SQL_CUSTOMERS c
LEFT JOIN TD_NL2SQL_ORDERS o
  ON c.CUSTOMER_ID = o.CUSTOMER_ID
GROUP BY
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    c.SEGMENT,
    c.PREFECTURE,
    c.RISK_RANK;

CREATE OR REPLACE VIEW V_TD_NL2SQL_OPEN_ORDERS AS
SELECT
    o.ORDER_ID,
    o.ORDER_DATE,
    o.STATUS,
    o.TOTAL_AMOUNT,
    c.CUSTOMER_NAME,
    d.DEPARTMENT_CODE,
    d.DEPARTMENT_NAME
FROM TD_NL2SQL_ORDERS o
JOIN TD_NL2SQL_CUSTOMERS c
  ON o.CUSTOMER_ID = c.CUSTOMER_ID
JOIN TD_NL2SQL_DEPARTMENTS d
  ON o.OWNER_DEPARTMENT_ID = d.DEPARTMENT_ID
WHERE o.STATUS IN ('NEW', 'REVIEW', 'APPROVED')
  AND o.TOTAL_AMOUNT > 0;
