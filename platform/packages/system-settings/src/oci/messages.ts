export type OciMessageKey = keyof typeof OCI_MESSAGES;

/** 文言を取り出し、`{name}` を params で置き換える（NL2SQL の t() と同じ動き）。 */
export function t(key: OciMessageKey, params?: Record<string, string | number>): string {
  let value: string = OCI_MESSAGES[key] ?? key;
  if (params) {
    for (const [name, replacement] of Object.entries(params)) {
      value = value.replace(new RegExp(`\\{${name}\\}`, "g"), String(replacement));
    }
  }
  return value;
}
